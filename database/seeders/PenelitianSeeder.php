                'doi_url' => 'https://doi.org/10.37058/jssainstek.v2i2.102',
                'cover' => 'images/jurnal/jssainstek_unsil.jpg',
                'cover_alt' => 'Cover Jurnal Siliwangi Seri Sains dan Teknologi Universitas Siliwangi',
                'article_id' => 'Vol. 2, No. 2',
            ],
        ];

        // Seed from oldest to newest so orderByDesc('tahun')->orderByDesc('id') preserves exact order and keeps new admin entries on top.
        foreach (array_reverse($data) as $row) {
            if (! empty($row['cover'])) {
                $source = public_path($row['cover']);
                $target = 'jurnal-covers/' . basename($row['cover']);

                if (is_file($source)) {
                    if (! Storage::disk('public')->exists($target)) {
                        Storage::disk('public')->put($target, file_get_contents($source));
                    }

                    $row['cover'] = $target;
                }
            }

            Penelitian::updateOrCreate(
                ['doi_label' => $row['doi_label']],
                array_merge($row, ['is_published' => true])
            );
        }
    }
